import { existsSync, readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { INTEGRATIONS, parseManifest, type IntegrationSpec } from "../packages/core/src/index.js";
import { DOC_MOCK_MODULES } from "../packages/testkit/src/index.js";
import { SANDBOX_CHECKS } from "./sandbox-checks.js";
import {
  PATHS,
  RegistryError,
  connectorFolders,
  generateFromFiles,
  generateFromModules,
  mergeManifest,
  moduleIds,
  readConnectorDocs,
  readManifestParts,
  renderCatalogIndex,
  renderCatalogTables,
  renderConnectorDocs,
  renderConnectorsIndex,
  renderFactoriesIndex,
  renderMockList,
  renderMocksIndex,
  renderSandboxChecksIndex,
  renderSandboxEnv,
  replaceBlock,
  stale,
  type ManifestParts,
} from "./registry.js";

const root = process.cwd();
const read = (file: string) => (existsSync(file) ? readFileSync(file, "utf8") : null);
const readText = (file: string) => readFileSync(file, "utf8");
const built = INTEGRATIONS.filter((i) => i.status === "built");
const builtIds = built.map((i) => i.id).sort();
const catalogIds = new Set(INTEGRATIONS.map((i) => i.id));
const manifest = parseManifest(JSON.parse(readText("secrets/manifest.json")));

describe("generated registry files", () => {
  it("are current; run npm run registry:write when this fails", async () => {
    expect(stale(generateFromFiles(root), read)).toEqual([]);
    expect(stale(await generateFromModules(root, readText), read)).toEqual([]);
  });

  it("are each marked as generated", async () => {
    for (const [file, content] of [...generateFromFiles(root), ...(await generateFromModules(root, readText))]) {
      expect(content, file).toMatch(/Generated (by|from) /);
    }
  });
});

describe("the generator", () => {
  it("sorts every list, whatever order the files are found in", () => {
    expect(renderConnectorsIndex(["b", "a"])).toMatch(/\.\/a\/index\.js[\s\S]*\.\/b\/index\.js/);
    for (const render of [renderCatalogIndex, renderFactoriesIndex, renderSandboxChecksIndex, renderMocksIndex]) {
      const out = render(["zeta", "alpha"]);
      expect(out.indexOf('import alpha from "./alpha.js"')).toBeLessThan(out.indexOf('import zeta from "./zeta.js"'));
      expect(out).toMatch(/alpha, zeta/);
    }
    expect(renderSandboxEnv([{ integration: "zeta", credentials: ["SANDBOX_ZETA_KEY"] }, { integration: "alpha", credentials: ["SANDBOX_ALPHA_B", "SANDBOX_ALPHA_A"] }])("  ")).toEqual([
      "  # Generated by npm run registry:write from each check in scripts/sandbox-checks/. Edit those, not this block.",
      "  SANDBOX_ALPHA_B: ${{ secrets.SANDBOX_ALPHA_B }}",
      "  SANDBOX_ALPHA_A: ${{ secrets.SANDBOX_ALPHA_A }}",
      "  SANDBOX_ZETA_KEY: ${{ secrets.SANDBOX_ZETA_KEY }}",
    ]);
    const docs = renderConnectorDocs([{ id: "zeta", text: "### Zeta\n\nz\n" }, { id: "alpha", text: "### Alpha\n\na\n" }]).join("\n");
    expect(docs.indexOf("### Alpha")).toBeLessThan(docs.indexOf("### Zeta"));
    const mocks = renderMockList([{ integration: "xero", covers: "X" }, { integration: "stuller", covers: "S" }], INTEGRATIONS);
    expect(mocks.filter((l) => l.startsWith("- "))).toEqual(["- S", "- X"]);
    expect(mocks).toContain("Where a vendor has a free sandbox (Xero so far), its mock is a stand-in until a developer account is set up for the nightly run.");
    expect(renderMockList([{ integration: "stuller", covers: "S" }], INTEGRATIONS).join("\n")).not.toContain("free sandbox");
  });

  it("puts every catalog entry in exactly one docs table", () => {
    const tables = renderCatalogTables(INTEGRATIONS);
    for (const i of INTEGRATIONS) expect(tables.filter((l) => l.startsWith(`| ${i.name} |`)), i.id).toHaveLength(1);
    expect(tables).toContain("| Shopify | R, W | Public API | Free sandbox | Yes | Built (Connector in @karatos/connectors: orders, refunds, fulfillments, products and customers, read-only) |");
    const orphan = { ...INTEGRATIONS[0]!, domain: "nowhere" } as unknown as IntegrationSpec;
    expect(() => renderCatalogTables([orphan])).toThrow(RegistryError);
  });

  it("replaces only what sits between a block's markers, keeping their indent", () => {
    const text = "a\n  # registry:x:start\n  old\n  # registry:x:end\nb";
    expect(replaceBlock(text, "f", "x", (indent) => [`${indent}new`])).toBe("a\n  # registry:x:start\n  new\n  # registry:x:end\nb");
    for (const broken of ["a", "registry:x:start", "registry:x:end\nregistry:x:start", "registry:x:start\nregistry:x:start\nregistry:x:end"]) {
      expect(() => replaceBlock(broken, "f", "x", () => [])).toThrow("needs exactly one registry:x:start");
    }
  });

  it("wants each docs section to start with its heading", () => {
    expect(() => renderConnectorDocs([{ id: "a", text: "no heading" }])).toThrow("docs/integrations/a.md");
  });
});

describe("the secrets manifest parts", () => {
  const entry = (name: string, requiredFor: string[]) => ({ name, kind: "secret", description: "d", requiredFor, howToGet: ["h"] });
  const parts = (over: Partial<ManifestParts> = {}): ManifestParts => ({
    instance: { entries: [entry("INSTANCE_KEY", ["instance"])] },
    shared: { entries: [entry("SHARED_KEY", [])] },
    connectors: [
      { file: "beta.json", data: { integration: "beta", uses: ["SHARED_KEY"], entries: [entry("BETA_KEY", ["integration:beta"])] } },
      { file: "alpha.json", data: { integration: "alpha", uses: ["SHARED_KEY"] } },
    ],
    ...over,
  });

  it("gives a shared setting the requiredFor of every connector that uses it, from their own files", () => {
    const merged = mergeManifest(parts());
    expect(merged.entries.map((e) => [e.name, e.requiredFor])).toEqual([
      ["INSTANCE_KEY", ["instance"]],
      ["SHARED_KEY", ["integration:alpha", "integration:beta"]],
      ["BETA_KEY", ["integration:beta"]],
    ]);
    expect(merged.$comment).toContain("Generated by npm run registry:write");
  });

  it("rejects parts that would leave two places saying different things", () => {
    const fails = (p: ManifestParts, message: string) => expect(() => mergeManifest(p)).toThrow(message);
    fails(parts({ connectors: [{ file: "alpha.json", data: { integration: "alpha", uses: ["NOPE"] } }] }), "uses NOPE, which isn't in shared.json");
    fails(parts({ connectors: [] }), "no connector uses SHARED_KEY");
    fails(parts({ connectors: [{ file: "alpha.json", data: { integration: "beta", uses: ["SHARED_KEY"] } }] }), 'alpha.json: integration must be "alpha"');
    fails(parts({ connectors: [{ file: "alpha.json", data: { integration: "alpha", uses: ["SHARED_KEY"], entries: [entry("A", ["integration:beta"])] } }] }), 'must be requiredFor ["integration:alpha"] only');
    fails(parts({ shared: { entries: [entry("SHARED_KEY", ["integration:alpha"])] } }), "shared.json: SHARED_KEY lists an integration");
    fails(parts({ instance: { entries: [entry("INSTANCE_KEY", ["instance"]), entry("BETA_KEY", ["integration:beta"])] } }), "BETA_KEY belongs in beta.json");
    fails(parts({ instance: { entries: [entry("SHARED_KEY", ["instance"])] } }), "SHARED_KEY is in the manifest twice");
  });

  it("names each per-connector file after a catalog id", () => {
    const ids = readManifestParts(root).connectors.map((c) => c.file.slice(0, -".json".length));
    expect(ids.length).toBeGreaterThan(0);
    for (const id of ids) expect(catalogIds.has(id), id).toBe(true);
  });
});

describe("every built connector", () => {
  it("has its connector, catalog entry, factory and docs section in its own files", () => {
    const connectorDirs = connectorFolders(root).filter((d) => catalogIds.has(d));
    expect(connectorDirs).toEqual(builtIds);
    expect(moduleIds(root, PATHS.catalog)).toEqual(builtIds);
    expect(moduleIds(root, PATHS.factories)).toEqual(builtIds);
    expect(readConnectorDocs(root).map((d) => d.id)).toEqual(builtIds);
  });

  it("documents each setting it needs in its own manifest file, required for it", () => {
    for (const spec of built) {
      for (const name of [...spec.settings, ...(spec.signIn ?? []).flat()]) {
        const entry = manifest.entries.find((e) => e.name === name);
        expect(entry, `${spec.id}: ${name}`).toBeDefined();
        expect(entry!.requiredFor.includes(`integration:${spec.id}`) || entry!.requiredFor.includes("instance"), `${spec.id}: ${name}`).toBe(true);
      }
    }
  });

  it("has a sandbox check, with its own test, when its vendor has a free sandbox, and only then", () => {
    const checks = SANDBOX_CHECKS.map((c) => c.integration).sort();
    expect(checks).toEqual(built.filter((i) => i.testWith === "sandbox").map((i) => i.id).sort());
    for (const id of checks) expect(existsSync(`${PATHS.sandboxChecks}/${id}.test.ts`), id).toBe(true);
  });

  it("has a mock built from the vendor's docs when there is no sandbox or sample file to test with", () => {
    const mocked = new Set(DOC_MOCK_MODULES.map((m) => m.integration));
    for (const m of DOC_MOCK_MODULES) expect(catalogIds.has(m.integration), m.integration).toBe(true);
    const needMock = built.filter((i) => i.testWith === "paid_account" || i.testWith === "partner" || i.testWith === "unknown");
    expect(needMock.filter((i) => !mocked.has(i.id)).map((i) => i.id)).toEqual([]);
  });
});
